package pl.mkn.tdw.features.releasesummary;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;
import pl.mkn.tdw.features.releasesummary.context.*;
import pl.mkn.tdw.features.releasesummary.report.*;
import pl.mkn.tdw.shared.ai.report.*;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;
class ReleaseSummaryAcceptanceTest {
    @Test void independentCrmInventoryCoversEveryObjectColumnConstraintDataUpdateAndRollback() {
        var evidence=ReleaseSummaryCrmFixture.evidence();assertTrue(evidence.sourceComplete(),evidence.gaps().toString());
        assertEquals(1,evidence.units().size());var unit=evidence.units().get(0);
        var counts=new TreeMap<String,Long>();unit.elements().forEach(e->counts.merge(e.kind(),1L,Long::sum));
        // Independently enumerated from the CRM migration, not generated by the parser.
        assertEquals(Map.ofEntries(Map.entry("ordering",1L),Map.entry("changeSet",1L),Map.entry("createTable",1L),
                Map.entry("column",6L),Map.entry("constraints",3L),Map.entry("createIndex",1L),Map.entry("addForeignKeyConstraint",1L),
                Map.entry("addUniqueConstraint",1L),Map.entry("createSequence",1L),Map.entry("update",1L),
                Map.entry("where",1L),Map.entry("rollback",1L),Map.entry("dropTable",1L),Map.entry("dropSequence",1L)),counts);
        assertTrue(unit.elements().stream().anyMatch(e->e.kind().equals("addForeignKeyConstraint")&&"CASCADE".equals(e.after().get("onDelete"))));
        assertEquals(Set.of("id","customer_id","label","label_state"),new HashSet<>(unit.elements().stream().filter(e->e.kind().equals("column")).map(e->e.after().get("name").toString()).toList()));
        assertTrue(evidence.sources().stream().anyMatch(source->source.content().equals(ReleaseSummaryCrmFixture.XML)));
    }
    @Test void orderOnlyChangesStayExplicitAndCustomCodeCannotClaimStructuralCompleteness() {
        var parser=new LiquibaseDocumentParser();
        var before=parser.parse("db.xml","<databaseChangeLog><changeSet id=\"first\"/><changeSet id=\"second\"/></databaseChangeLog>");
        var after=parser.parse("db.xml","<databaseChangeLog><changeSet id=\"second\"/><changeSet id=\"first\"/></databaseChangeLog>");
        assertNotEquals(parser.childOrder(before.roots().get(0)),parser.childOrder(after.roots().get(0)));
        assertFalse(parser.parse("db.xml","<databaseChangeLog><customChange class=\"crm.Labels\"/></databaseChangeLog>").structured());
        assertFalse(parser.parse("db.xml","<databaseChangeLog xmlns:crm=\"urn:crm:extension\"><crm:column name=\"label\"/></databaseChangeLog>").structured());
        assertFalse(parser.parse("db.sql","--liquibase formatted sql\n--changeset crm:labels\nALTER TABLE customer ADD label text;").structured());
    }
    @Test void largeTablesPreserveAllRowsAndDeclaredAiGapsCannotBecomeCompleted() {
        var rows=new ArrayList<List<String>>();
        for(int i=0;i<2000;i++)rows.add(List.of("crm-"+i,"Opis etykiety | "+i));
        var markdown=ReleaseSummaryTables.table(List.of("id","opis"),rows);
        assertEquals(rows,ReleaseSummaryTables.parse(markdown).get(0).rows());
        var reports=new ReleaseSummaryReportService(new ObjectMapper());var complete=ReleaseSummaryReportTest.completed(reports,true);
        var meta=new AnalysisReportMeta(List.of(),List.of(),List.of(),List.of("Nie potwierdzono celu funkcjonalnego."),null,List.of());
        var report=new AnalysisReport(complete.reportId(),complete.header(),complete.subHeader(),complete.markdownSummary(),complete.sections(),meta);
        assertEquals("PARTIAL",reports.project(report,ReleaseSummaryReportTest.evidence(true),reports.initialSources(ReleaseSummaryReportTest.SCOPE,ReleaseSummaryReportTest.evidence(true))).status());
    }
    @Test void longSourceCellsHaveUniquePatchTargetsAndLiteralSourceValuesAreNotPlaceholders() {
        var reports=new ReleaseSummaryReportService(new ObjectMapper());
        var base=ReleaseSummaryReportTest.evidence(true);
        var elements=List.of("first","second").stream().map(id->new pl.mkn.tdw.features.releasesummary.contract.ReleaseSummaryEvidence.Element(
                id,"column","/changeSet/column:"+id,null,Map.<String,Object>of("name",id,"defaultValue","DO_UZUPELNIENIA","remarks","CRM ".repeat(50000)))).toList();
        var evidence=new pl.mkn.tdw.features.releasesummary.contract.ReleaseSummaryEvidence(base.sources(),List.of(
                new pl.mkn.tdw.features.releasesummary.contract.ReleaseSummaryEvidence.Unit("unit1","customer","db/customer.xml","ADDED",null,
                        ReleaseSummaryReportTest.SOURCE,elements,true)),List.of(),List.of(),1,true);
        var scaffold=reports.scaffold("crm-report",ReleaseSummaryReportTest.SCOPE,evidence);
        var sections=new ArrayList<>(scaffold.sections());var detail=sections.get(4);var text=detail.markdown();
        for(var element:elements) {
            var marker="DO_UZUPELNIENIA_"+element.elementId()+"_TECH";
            assertEquals(text.indexOf(marker),text.lastIndexOf(marker));assertTrue(text.contains(marker));
            text=text.replace(marker,"Wartość domyślna opisuje stan etykiety klienta.")
                    .replace("DO_UZUPELNIENIA_"+element.elementId()+"_FUNCTION","Brak kodu wyjaśniającego cel pola.");
        }
        var known=reports.initialSources(ReleaseSummaryReportTest.SCOPE,evidence);
        reports.validateSection(detail.id(),text,evidence,known);
        sections.set(4,new AnalysisReportSection(detail.id(),detail.title(),detail.order(),text,detail.meta()));
        var report=new AnalysisReport(scaffold.reportId(),scaffold.header(),scaffold.subHeader(),scaffold.markdownSummary(),sections,scaffold.meta());
        assertEquals(2,reports.project(report,evidence,known).documentedElements());
    }
}
